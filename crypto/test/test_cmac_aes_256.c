static void run_test_vector(int iter, const struct test_vectors *t)
{
	uint8_t mac[BLOCK_SIZE];
	int i;

#define FIXED_MSG_LEN(t) \
	(((t)->Msg_size_in_bytes != 1) ? (t)->Msg_size_in_bytes \
				       : (*(t)->Msg == 0x00) ? 0 : 1)

	cmac_aes((uint8_t *)t->Key,
		 (t->Key_size_in_bytes * 8),
		 (uint8_t *)t->Msg,
		 FIXED_MSG_LEN(t),
		 mac);

	printf("%d: ", iter);
	for (i = 0; i < t->Mac_size_in_bytes; i++)
		printf("%02x", mac[i]);
	printf("\n");

	assert(!memcmp(mac, t->Mac, t->Mac_size_in_bytes));
}

